const { Document, Packer, Paragraph, TextRun, ImageRun, AlignmentType } = require('docx');

/**
 * Builds a Microsoft Word (.docx) buffer for an array of questions.
 * Perfectly formatted for printing, offline storage, and re-import into ExamShield.
 *
 * @param {Array} questions - Array of question objects from database
 * @param {string} topicName - Selected topic or 'All Topics'
 * @returns {Promise<Buffer>} - Buffer containing the generated .docx file
 */
async function exportQuestionsToDocx(questions, topicName = 'All Topics') {
  const children = [];

  // Header Title
  children.push(
    new Paragraph({
      alignment: AlignmentType.CENTER,
      children: [
        new TextRun({
          text: 'EXAMSHIELD LAN 🛡️ - QUESTION BANK',
          bold: true,
          size: 28,
          color: '312E81'
        })
      ]
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      children: [
        new TextRun({
          text: `Topic: ${topicName || 'All Topics'}  |  Total Questions: ${questions.length}  |  Generated by ExamShield Teacher Center`,
          italics: true,
          size: 19,
          color: '4F46E5'
        })
      ]
    }),
    new Paragraph({
      children: [new TextRun({ text: '' })]
    })
  );

  questions.forEach((q, idx) => {
    const qNum = idx + 1;
    const qTopic = q.topic || topicName || 'General';
    const qText = q.question_text || (q.question_html ? q.question_html.replace(/<[^>]+>/g, '').trim() : `Question ${qNum}`);

    // Question Prompt
    children.push(
      new Paragraph({
        children: [
          new TextRun({
            text: `${qNum}. [${qTopic}] `,
            bold: true,
            color: '4338CA',
            size: 22
          }),
          new TextRun({
            text: qText,
            bold: true,
            color: '0F172A',
            size: 22
          })
        ]
      })
    );

    // Extract embedded Base64 image(s) from question_html if present
    if (q.question_html && typeof q.question_html === 'string') {
      const imgRegex = /data:image\/(?:png|jpeg|jpg|webp);base64,([A-Za-z0-9+/=]+)/g;
      let match;
      while ((match = imgRegex.exec(q.question_html)) !== null) {
        if (match[1]) {
          try {
            const imgBuf = Buffer.from(match[1], 'base64');
            children.push(
              new Paragraph({
                children: [
                  new ImageRun({
                    data: imgBuf,
                    transformation: { width: 340, height: 190 }
                  })
                ]
              })
            );
          } catch (imgErr) {
            console.warn(`[docxExporter] Could not embed image for question ${qNum}:`, imgErr.message);
          }
        }
      }
    }

    // Options
    let options = q.options;
    if (typeof options === 'string') {
      try { options = JSON.parse(options); } catch (e) { options = []; }
    }
    if (!Array.isArray(options)) options = [];

    options.forEach((opt, oIdx) => {
      const letter = opt.letter || (opt.key ? String.fromCharCode(65 + parseInt(opt.key, 10)) : String.fromCharCode(65 + oIdx));
      let text = '';
      if (typeof opt === 'string') {
        text = opt;
      } else if (opt && opt.text) {
        text = opt.text;
      } else if (opt && opt.html) {
        text = opt.html.replace(/<[^>]+>/g, '').trim();
      }

      children.push(
        new Paragraph({
          indent: { left: 400 },
          children: [
            new TextRun({
              text: `${letter}. `,
              bold: true,
              color: '334155',
              size: 21
            }),
            new TextRun({
              text: text || `Option ${letter}`,
              color: '334155',
              size: 21
            })
          ]
        })
      );

      // Check if option has an embedded image
      const optHtml = (opt && opt.html) ? opt.html : '';
      let optImgBase64 = (opt && opt.image_base64) ? opt.image_base64 : null;
      if (!optImgBase64 && optHtml) {
        const m = optHtml.match(/data:image\/(?:png|jpeg|jpg|webp);base64,([A-Za-z0-9+/=]+)/);
        if (m && m[1]) optImgBase64 = m[1];
      }
      if (optImgBase64) {
        try {
          const rawBase64 = optImgBase64.replace(/^data:image\/[a-z]+;base64,/, '');
          const optImgBuf = Buffer.from(rawBase64, 'base64');
          children.push(
            new Paragraph({
              indent: { left: 600 },
              children: [
                new ImageRun({
                  data: optImgBuf,
                  transformation: { width: 220, height: 120 }
                })
              ]
            })
          );
        } catch (imgErr) {
          console.warn(`[docxExporter] Could not embed option ${letter} image:`, imgErr.message);
        }
      }
    });

    // Determine Correct Answers (Mapped to Letters: A, B, C...)
    let correctLetters = [];
    if (Array.isArray(q.correct_answers) && q.correct_answers.length > 0) {
      correctLetters = q.correct_answers.map(a => {
        if (/^[A-Z]$/i.test(a)) return a.toUpperCase();
        const found = options.find(o => o.key === a || o.letter === a);
        return found ? found.letter : a;
      });
    } else if (Array.isArray(q.correct_keys) && q.correct_keys.length > 0) {
      correctLetters = q.correct_keys.map(k => {
        if (/^[A-Z]$/i.test(k)) return k.toUpperCase();
        const found = options.find(o => o.key === k || o.letter === k);
        return found ? found.letter : k;
      });
    } else if (typeof q.correct_answers_json === 'string') {
      try {
        const parsed = JSON.parse(q.correct_answers_json);
        correctLetters = parsed.map(k => {
          if (/^[A-Z]$/i.test(k)) return k.toUpperCase();
          const found = options.find(o => o.key === k);
          return found ? found.letter : k;
        });
      } catch (e) {
        correctLetters = ['A'];
      }
    }

    if (correctLetters.length === 0) correctLetters = ['A'];
    const answerStr = correctLetters.join(', ');
    const isMulti = !!q.is_multiple_choice || correctLetters.length > 1;

    // Answer Line (Follows ExamShield DOCX standard format)
    children.push(
      new Paragraph({
        indent: { left: 400 },
        children: [
          new TextRun({
            text: `Answer: ${answerStr || 'A'} (${isMulti ? 'multiple' : 'single'})`,
            bold: true,
            color: '059669',
            size: 21
          })
        ]
      }),
      // Spacer paragraph between questions
      new Paragraph({
        children: [new TextRun({ text: '' })]
      })
    );
  });

  const doc = new Document({
    sections: [{
      properties: {
        page: {
          margin: { top: 1000, right: 1000, bottom: 1000, left: 1000 }
        }
      },
      children
    }]
  });

  return await Packer.toBuffer(doc);
}

module.exports = {
  exportQuestionsToDocx
};
