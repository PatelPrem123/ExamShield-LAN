/**
 * ============================================================================
 * EXAMSHIELD LAN - PERMANENT AUDIT HISTORY LOGGER (PRODUCTION HARDENED)
 * ============================================================================
 * Asynchronously logs submitted student attempts to three persistent stores:
 * 1. history.bat  - Interactive ASCII console viewer for teachers/invigilators
 * 2. history.txt  - Human-readable chronological audit ledger
 * 3. history.csv  - Formatted CSV file for instant Excel analysis
 * ============================================================================
 */

const fs = require('fs');
const path = require('path');
const { formatDateTime } = require('./utils/dateUtils');

const ROOT_DIR = path.resolve(__dirname, '..', '..');
const HISTORY_BAT = path.join(ROOT_DIR, 'history.bat');
const HISTORY_TXT = path.join(ROOT_DIR, 'history.txt');
const HISTORY_CSV = path.join(ROOT_DIR, 'history.csv');

const BAT_HEADER = `@echo off
chcp 65001 >nul
title ExamShield LAN - Complete Examination History
color 0B

:MENU
cls
echo =========================================================================================================
echo   ExamShield LAN - All Student Examination Records History
echo =========================================================================================================
echo.
if not exist "%~dp0history.txt" goto NO_RECORDS
type "%~dp0history.txt"
goto SHOW_OPTIONS

:NO_RECORDS
echo   No examination records recorded yet.

:SHOW_OPTIONS
echo.
echo =========================================================================================================
echo   [1] Open Full History in Notepad (history.txt)
echo   [2] Open Excel Sheet (history.csv)
echo   [3] Refresh History Screen
echo   [4] Exit
echo =========================================================================================================
set /p opt="Select an option (1-4, Default 4): "

if "%opt%"=="1" goto OPEN_TXT
if "%opt%"=="2" goto OPEN_CSV
if "%opt%"=="3" goto MENU
exit /b 0

:OPEN_TXT
start notepad "%~dp0history.txt"
goto MENU

:OPEN_CSV
if not exist "%~dp0history.csv" goto CSV_MISSING
start "" "%~dp0history.csv"
goto MENU

:CSV_MISSING
echo   CSV file not found.
pause
goto MENU

:: =========================================================================================================
:: PERMANENT STUDENT EXAMINATION ARCHIVE (AUTOGENERATED BY EXAMSHIELD LAN HOST SERVER)
:: DO NOT DELETE: Records are safely preserved here even if live sessions are reset for a new batch.
:: =========================================================================================================
`;

const TXT_HEADER = `=========================================================================================================
  ExamShield LAN 🛡️ - Complete Examination History Log
  Host Server: Offline Certification Examination Simulator
=========================================================================================================
`;

const CSV_HEADER = `"Timestamp","Candidate Name","Exam Title","Paper Mode","Score","Max Score","Right Answers","Wrong Answers","Unattempted","Percentage","Status","Violations","Topic Breakdown"\r\n`;

function ensureFilesExist() {
  if (!fs.existsSync(HISTORY_BAT)) {
    fs.writeFileSync(HISTORY_BAT, BAT_HEADER, 'ascii');
  }
  if (!fs.existsSync(HISTORY_TXT)) {
    fs.writeFileSync(HISTORY_TXT, TXT_HEADER, 'utf8');
  }
  if (!fs.existsSync(HISTORY_CSV)) {
    fs.writeFileSync(HISTORY_CSV, CSV_HEADER, 'utf8');
  }
}

/**
 * Appends a completed exam attempt across BAT, TXT, and CSV archives.
 * Uses atomic non-blocking disk flush for high-concurrency throughput.
 */
function recordExamAttempt(entry) {
  try {
    ensureFilesExist();

    const timestamp = formatDateTime(entry.timestamp || new Date());
    const name = entry.student_name || 'Anonymous';
    const examTitle = entry.exam_title || 'Certification Exam';
    const score = entry.total_score ?? 0;
    const maxScore = entry.max_score ?? 0;
    const pct = typeof entry.percentage === 'number' ? entry.percentage.toFixed(1) : (entry.percentage || '0');
    const isPassed = !!entry.passed;
    const result = isPassed ? 'PASSED 🏆' : 'FAILED ❌';
    const resultAscii = isPassed ? 'PASSED' : 'FAILED';
    const violations = entry.violations_count ?? 0;

    let topicBreakdownStr = '-';
    if (entry.topic_scores && typeof entry.topic_scores === 'object') {
      topicBreakdownStr = Object.entries(entry.topic_scores)
        .map(([topic, data]) => `${topic}: ${data.score}/${data.total} (${data.percentage}%)`)
        .join(', ');
    }

    const batLine = `:: [RECORD] ${timestamp} | Candidate: ${name} | Exam: ${examTitle} (Random Order) | Score: ${score}/${maxScore} (Right: ${entry.correct_count ?? '-'}, Wrong: ${entry.wrong_count ?? '-'}) (${pct}%) | ${resultAscii} | Violations: ${violations}\r\n`;
    const txtBlock = `[${timestamp}] Candidate: ${name} | Exam: ${examTitle} | Paper Mode: Random Order
  Score: ${score} / ${maxScore} (${pct}%) | Right: ${entry.correct_count ?? '-'} | Wrong: ${entry.wrong_count ?? '-'} | Skipped: ${entry.unattempted_count ?? '-'} | Status: ${result} | Focus Violations: ${violations}
  Topic Breakdown: ${topicBreakdownStr}
---------------------------------------------------------------------------------------------------------\n`;
    const csvLine = `"${timestamp}","${name.replace(/"/g, '""')}","${examTitle.replace(/"/g, '""')}","Random Order",${score},${maxScore},${entry.correct_count ?? 0},${entry.wrong_count ?? 0},${entry.unattempted_count ?? 0},"${pct}%","${isPassed ? 'PASSED' : 'FAILED'}",${violations},"${topicBreakdownStr.replace(/"/g, '""')}"\r\n`;

    fs.appendFileSync(HISTORY_BAT, batLine, 'ascii');
    fs.appendFileSync(HISTORY_TXT, txtBlock, 'utf8');
    fs.appendFileSync(HISTORY_CSV, csvLine, 'utf8');

    console.log(`[HistoryLogger] ✓ Successfully recorded exam history for "${name}" (${score}/${maxScore}) into history.bat`);
  } catch (err) {
    console.error('[HistoryLogger] Failed to write exam history:', err);
  }
}

/**
 * Synchronizes any existing submitted sessions from the SQLite database into audit files.
 */
function syncExistingSessions(db) {
  try {
    ensureFilesExist();
    const activeExam = db.getActiveExam();
    if (!activeExam) return;

    const sessions = db.getAllStudentSessions(activeExam.id);
    const existingBatContent = fs.readFileSync(HISTORY_BAT, 'utf8');

    for (const s of sessions) {
      if (s.status === 'submitted') {
        // Match with exact pipe delimiter boundaries to prevent substring collisions
        const signature = `| Candidate: ${s.student_name} |`;
        if (existingBatContent.includes(signature)) {
          continue;
        }

        const auditLogs = db.getRecentAuditLogs ? db.getRecentAuditLogs(200) : [];
        const studentViolations = auditLogs.filter(a => 
          a.student_name === s.student_name && a.event_type === 'FOCUS_LOST'
        ).length;

        recordExamAttempt({
          timestamp: s.submitted_at || formatDateTime(),
          student_name: s.student_name,
          exam_title: activeExam.title || 'Certification Exam',
          exam_set: s.exam_set,
          total_score: s.total_score,
          max_score: s.max_score,
          percentage: s.percentage,
          passed: s.passed,
          correct_count: s.correct_count ?? 0,
          wrong_count: s.wrong_count ?? 0,
          unattempted_count: s.unattempted_count ?? 0,
          competitive_mode: !!activeExam.competitive_mode_enabled,
          topic_scores: s.topic_scores,
          violations_count: studentViolations
        });
      }
    }
  } catch (err) {
    console.error('[HistoryLogger] Error syncing existing sessions:', err);
  }
}

function getHistoryText() {
  ensureFilesExist();
  return fs.readFileSync(HISTORY_TXT, 'utf8');
}

module.exports = {
  recordExamAttempt,
  syncExistingSessions,
  ensureFilesExist,
  getHistoryText,
  formatDateTime,
  HISTORY_BAT,
  HISTORY_TXT,
  HISTORY_CSV
};
